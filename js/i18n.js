export const LANGS = Object.keys(STRINGS);

export function translate(lang, key, vars = {}) {
  const s = (STRINGS[lang] && STRINGS[lang][key]) ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`));
}

/** Pick the saved language, else Bangla for Bangla browsers, else English. */
export function detectLang(saved, navigatorLang = "en", fallback = "en") {
  if (LANGS.includes(saved)) return saved;
  if (String(navigatorLang).toLowerCase().startsWith("bn")) return "bn";
  return LANGS.includes(fallback) ? fallback : "en";
}
